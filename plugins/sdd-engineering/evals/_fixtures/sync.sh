#!/usr/bin/env bash
# Regenerates every case's fixture.sh from todo-cli.sh. A scaffold script must
# live in its case directory, so the shared fixture is copied, not sourced.
# Each case declares its variant in fixture.env (SPEC_STATUS=…, NO_TESTS=…).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
for env in "$here"/../*/fixture.env; do
  case_dir="$(dirname "$env")"
  { echo '#!/usr/bin/env bash'; echo '# GENERATED by evals/_fixtures/sync.sh — edit _fixtures/todo-cli.sh instead.';
    sed 's/^/export /' "$env"; tail -n +2 "$here/todo-cli.sh"; } > "$case_dir/fixture.sh"
  chmod +x "$case_dir/fixture.sh"
done
